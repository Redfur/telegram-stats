-- Настоящая причина подвисания переимпорта на реконсиляции участников
-- (db/import.rs) — не связана с таймлайном (0011/0012), баг существует
-- с Фазы 3 (слияние участников). `DELETE FROM people WHERE id = ?` в
-- цикле по каждому участнику временного чата запускает у SQLite
-- неявную FK-проверку (`ON DELETE SET NULL`/`CASCADE`) по каждой
-- ссылающейся таблице — без индекса на голом `person_id` (только
-- составные `(chat_id, person_id)`, где `chat_id` — ведущая колонка,
-- бесполезные для проверки без него) это полный скан таблицы на КАЖДОГО
-- удаляемого участника. `messages` — самая крупная таблица в приложении
-- (потенциально миллионы строк по всем чатам сразу): на чате с тысячами
-- участников это превращало реконсиляцию в многоминутное подвисание без
-- ошибки и без реакции на «Отменить» (тот же класс бага, что чинила
-- 0012 для куда более мелких membership_events/chat_events).
CREATE INDEX idx_messages_person_id ON messages(person_id);
CREATE INDEX idx_reaction_actors_person_id ON reaction_actors(person_id);
-- people.merged_into — самоссылающийся FK (миграция 0003), та же
-- проверка при DELETE FROM people, но по самой people (обычно куда
-- меньше messages) — добавлен заодно, для полноты.
CREATE INDEX idx_people_merged_into ON people(merged_into);
